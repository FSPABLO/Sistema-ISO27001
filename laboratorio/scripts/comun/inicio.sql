@comun/config.sql
SET ECHO OFF FEEDBACK OFF VERIFY OFF HEADING ON PAGESIZE 200 LINESIZE 220
SET TRIMOUT ON TRIMSPOOL ON TAB OFF SQLBLANKLINES ON
WHENEVER SQLERROR CONTINUE
CONNECT / AS SYSDBA
ALTER SESSION SET CONTAINER = &PDB;
-- SERVEROUTPUT solo se activa con una conexion abierta
SET SERVEROUTPUT ON SIZE UNLIMITED FORMAT WRAPPED
ALTER SESSION SET NLS_DATE_FORMAT = 'YYYY-MM-DD HH24:MI:SS';
